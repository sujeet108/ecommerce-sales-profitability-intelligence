SHIP = {"Standard Class": (0.60, 4, 7), "Second Class": (0.20, 2, 5), "First Class": (0.15, 1, 3), "Same Day": (0.05, 0, 0)}


def build_catalog(rng):
    rows, n = [], 0
    for cat, sub, noun, k, lo, hi, bm, prop, pop in SUBCATS:
        for i in range(k):
            n += 1
            list_price = round(float(np.exp(rng.uniform(np.log(lo), np.log(hi)))), 2)
            rows.append(dict(
                product_id=f"{cat[:3].upper()}-{sub[:2].upper()}-{10000 + n}",
                product_name=f"{BRANDS[int(rng.integers(len(BRANDS)))]} {noun} {chr(65 + i % 26)}{100 + n}",
                category=cat, sub_category=sub, list_price=list_price,
                unit_cost=round(list_price * (1 - bm) * float(rng.normal(1, 0.05)), 2),
                propensity=prop, weight=pop * float(rng.lognormal(0, 0.7))))
    return pd.DataFrame(rows)


def build_geo(rng):
    geo = pd.DataFrame(CITIES, columns=["city", "state", "region", "zip3"])
    geo["zips"] = [[f"{z}{int(rng.integers(1, 99)):02d}" for _ in range(2)] for z in geo.zip3]
    geo["weight"] = rng.lognormal(0, 0.5, len(geo))
    return geo


def generate_clean_lines(rng):
    cat, geo = build_catalog(rng), build_geo(rng)
    pw = (cat.weight / cat.weight.sum()).to_numpy()
    gw = (geo.weight / geo.weight.sum()).to_numpy()

    cust = pd.DataFrame({
        "customer_id": [f"{FIRST[i % 30][0]}{LAST[(i * 7) % 30][0]}-{10000 + i}" for i in range(N_CUSTOMERS)],
        "customer_name": [f"{FIRST[int(rng.integers(30))]} {LAST[int(rng.integers(30))]}" for _ in range(N_CUSTOMERS)],
        "segment": rng.choice(["Consumer", "Corporate", "Home Office"], N_CUSTOMERS, p=[.52, .30, .18]),
        "home_city": rng.choice(len(geo), N_CUSTOMERS, p=gw),
        "activity": rng.gamma(1.2, 1.0, N_CUSTOMERS)})
    cw = (cust.activity / cust.activity.sum()).to_numpy()

    yrs = list(YEAR_WEIGHTS)
    yp = np.array(list(YEAR_WEIGHTS.values())); yp = yp / yp.sum()
    mp = MONTH_WEIGHTS / MONTH_WEIGHTS.sum()
    orders = pd.DataFrame({
        "year": rng.choice(yrs, N_ORDERS, p=yp), "month": rng.choice(np.arange(1, 13), N_ORDERS, p=mp),
        "day": rng.integers(1, 29, N_ORDERS), "cust": rng.choice(N_CUSTOMERS, N_ORDERS, p=cw)})
    orders["order_date"] = pd.to_datetime(dict(year=orders.year, month=orders.month, day=orders.day))
    orders = orders.sort_values("order_date", kind="stable").reset_index(drop=True)
    orders["order_id"] = [f"US-{d.year}-{100001 + i}" for i, d in enumerate(orders.order_date)]

    qty_vals = np.arange(1, 15)
    qty_p = np.array([.14, .20, .20, .16, .11, .07, .04, .03, .02, .01, .01, .005, .003, .002]); qty_p /= qty_p.sum()
    modes = list(SHIP); mode_p = np.array([SHIP[m][0] for m in modes])
    recs = []
    for o in orders.itertuples():
        c = cust.iloc[o.cust]
        city = geo.iloc[int(c.home_city)] if rng.random() < 0.85 else geo.iloc[int(rng.choice(len(geo), p=gw))]
        postal = city.zips[int(rng.integers(2))]
        mode = modes[int(rng.choice(4, p=mode_p))]
        lag = int(rng.integers(SHIP[mode][1], SHIP[mode][2] + 1))
        n_lines = int(rng.choice(np.arange(1, 8), p=[.38, .28, .17, .09, .05, .02, .01]))
        for pi in rng.choice(len(cat), n_lines, replace=False, p=pw):
            p = cat.iloc[int(pi)]
            qty = int(rng.choice(qty_vals, p=qty_p))
            p_disc = min(0.92, p.propensity * REGION_DISC_MULT[city.region])
            disc = 0.0
            if rng.random() < p_disc:
                disc = float(rng.choice(DISC_LEVELS, p=DISC_P_HIGH if p.propensity >= 0.7 else DISC_P_LOW))
            sales = round(p.list_price * float(rng.normal(1, 0.02)) * qty * (1 - disc), 2)
            profit = round(sales - p.unit_cost * qty, 2)
            recs.append(dict(
                order_id=o.order_id, order_date=o.order_date, ship_date=o.order_date + pd.Timedelta(days=lag),
                ship_mode=mode, customer_id=c.customer_id, customer_name=c.customer_name, segment=c.segment,
                country="United States", city=city.city, state=city.state, postal_code=postal, region=city.region,
                product_id=p.product_id, category=p.category, sub_category=p.sub_category,
                product_name=p.product_name, sales=sales, quantity=qty, discount=disc, profit=profit))
    return pd.DataFrame(recs)


def main(out_dir: Path = Path(__file__).resolve().parents[1] / "data/raw") -> None:
    rng = np.random.default_rng(SEED)
    df = generate_clean_lines(rng)
    df["is_return"] = False

    # --- legitimate returns: partial reversal of an earlier sale (negative qty, sales and profit)
    ret = df[(df.quantity >= 2)].sample(10, random_state=SEED).copy()
    ret["quantity"] = -1
    ret["sales"] = -(df.loc[ret.index, "sales"] / df.loc[ret.index, "quantity"]).round(2)
    ret["profit"] = -(df.loc[ret.index, "profit"] / df.loc[ret.index, "quantity"]).round(2)
    ret["is_return"] = True
    df = pd.concat([df, ret], ignore_index=True)
    df = df.sort_values(["order_date", "order_id", "is_return"], kind="stable").reset_index(drop=True)
    df.insert(0, "row_id", np.arange(1, len(df) + 1))

    pool = iter(rng.permutation(df.index[~df.is_return]))
    def take(k): return [next(pool) for _ in range(k)]
    manifest = {"seed": SEED, "note": "Answer key of planted problems. Used only to test the cleaning code."}

    # --- planted numeric / date problems
    i = take(6); cost = df.loc[i, "sales"] - df.loc[i, "profit"]
    df.loc[i, "sales"] = (df.loc[i, "sales"] * 40).round(2); df.loc[i, "profit"] = (df.loc[i, "sales"] - cost).round(2)
    manifest["price_outliers_x40"] = len(i)
    i = take(8); df.loc[i, "quantity"] = 0; manifest["quantity_zero_with_positive_sales"] = len(i)
    i = take(5); df.loc[i, "quantity"] = -df.loc[i, "quantity"]; manifest["quantity_negative_with_positive_sales"] = len(i)
    i = take(6); df.loc[i, "sales"] = 0.0; manifest["sales_zero_with_positive_quantity"] = len(i)
    i = take(4); df.loc[i, "discount"] = rng.choice([20.0, 30.0, 35.0, 50.0], 4); manifest["discount_gt_1_percent_entry_error"] = len(i)
    i = take(14); df.loc[i, "ship_date"] = df.loc[i, "order_date"] - pd.to_timedelta(rng.integers(1, 6, 14), unit="D")
    manifest["ship_date_before_order_date"] = len(i)

    # --- convert to raw text-like formats
    raw = pd.DataFrame({
        "Row ID": df.row_id.astype(str), "Order ID": df.order_id,
        "Order Date": df.order_date.dt.strftime("%Y-%m-%d"), "Ship Date": df.ship_date.dt.strftime("%Y-%m-%d"),
        "Ship Mode": df.ship_mode, "Customer ID": df.customer_id, "Customer Name": df.customer_name,
        "Segment": df.segment, "Country": df.country, "City": df.city, "State": df.state,
        "Postal Code": df.postal_code.astype(int).astype(str),   # leading zeros are lost, as in many real exports
        "Region": df.region, "Product ID": df.product_id, "Category": df.category,
        "Sub-Category": df.sub_category, "Product Name": df.product_name,
        "Sales": df.sales.map("{:.2f}".format), "Quantity": df.quantity.astype(str),
        "Discount": df.discount.map("{:g}".format), "Profit": df.profit.map("{:.2f}".format)})
    n = len(raw); pool = iter(rng.permutation(n)); take = lambda k: [next(pool) for _ in range(k)]
    manifest["postal_code_leading_zero_lost"] = int((df.postal_code.str.startswith("0")).sum())

    i = take(int(n * 0.03))
    for c in ["Order Date", "Ship Date"]:
        raw.loc[i, c] = pd.to_datetime(raw.loc[i, c]).dt.strftime("%d-%b-%Y")
    manifest["dates_in_dd-Mon-yyyy_format_rows"] = len(i)
    i = take(40); raw.loc[i, "Postal Code"] = np.nan; manifest["missing_postal_code"] = len(i)
    i = take(30); raw.loc[i, "Customer Name"] = np.nan; manifest["missing_customer_name"] = len(i)
    i = [j for j in take(60) if raw.at[j, "Category"] == "Furniture"][:12]
    raw.loc[i, "Category"] = "Furnitures"; manifest["category_typo_Furnitures"] = len(i)
    i = take(25); raw.loc[i, "Country"] = rng.choice(["USA", "US"], 25); manifest["country_alias"] = len(i)
    noisy = 0
    for c in ["Region", "Segment", "Ship Mode", "Category", "Sub-Category"]:
        i = take(int(n * 0.015))
        for j in i:
            v = raw.at[j, c]
            if v == "Furnitures": continue
            raw.at[j, c] = [v.upper(), v.lower(), " " + v, v + " "][int(rng.integers(4))]; noisy += 1
    manifest["case_or_whitespace_noise_cells"] = noisy

    # --- exact duplicate rows (same Row ID, identical values)
    d = raw.iloc[take(45)]
    manifest["exact_duplicate_rows"] = len(d)
    raw = pd.concat([raw, d]).sort_values("Row ID", key=lambda s: s.astype(int), kind="stable").reset_index(drop=True)

    manifest["valid_return_rows_planted"] = int(df.is_return.sum())
    manifest["raw_rows_written"] = len(raw)
    out_dir.mkdir(parents=True, exist_ok=True)
    raw.to_csv(out_dir / "superstore_synthetic_raw.csv", index=False, encoding="utf-8")
    (out_dir / "injected_issues.json").write_text(json.dumps(manifest, indent=2))
    print(f"Wrote {len(raw):,} raw rows -> {out_dir / 'superstore_synthetic_raw.csv'}")
    print(json.dumps(manifest, indent=2))


if __name__ == "__main__":
    main()
