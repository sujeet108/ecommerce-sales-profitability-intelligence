"""
Generate a SYNTHETIC Superstore-style retail dataset.

IMPORTANT: Every row is randomly generated by this script. It does NOT describe
a real company, real customers, or real sales. Product brands, customer names
and all figures are fictional. City/state names are real places used only as
geography labels.

The output deliberately contains realistic data-quality problems (duplicates,
mixed date formats, typos, invalid quantities, ...) so the cleaning stage has
real work to do. The exact number of planted problems is written to
data/raw/injected_issues.json and is used ONLY as an answer key to check that
the cleaning code finds them.

Usage:  python src/generate_synthetic_data.py
"""
from __future__ import annotations

