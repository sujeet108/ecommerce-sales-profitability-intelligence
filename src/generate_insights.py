"""Writes reports/business_insights.md. Every number is computed here from the clean data;
assertions stop the script if a qualitative claim stops being true (e.g. after changing the data)."""
from pathlib import Path

import pandas as pd

ROOT = Path(__file__).resolve().parents[1]


def md_table(d: pd.DataFrame) -> str:
    return "| " + " | ".join(d.columns) + " |\n|" + "---|" * len(d.columns) + "\n" + "\n".join(
        "| " + " | ".join(str(v) for v in r) + " |" for r in d.itertuples(index=False))


def main():
    df = pd.read_csv(ROOT / "data/processed/superstore_clean.csv", parse_dates=["order_date"])
    sl = df[df.is_return == 0]
    rev, pro = df.sales.sum(), df.profit.sum()
    prod = df.groupby(["product_name", "sub_category"]).agg(revenue=("sales", "sum"), profit=("profit", "sum")).reset_index()
    prod["margin_pct"] = (prod.profit / prod.revenue * 100).round(1)
    fmt = lambda d: d.assign(revenue=d.revenue.map("{:,.0f}".format), profit=d.profit.map("{:,.0f}".format))

    top_rev, top_pro = prod.nlargest(5, "revenue"), prod.nlargest(5, "profit")
    q75 = prod.revenue.quantile(.75)
    hs = prod[(prod.revenue >= q75) & (prod.margin_pct < 10)].sort_values("revenue", ascending=False)

    reg = df.groupby("region").agg(revenue=("sales", "sum"), profit=("profit", "sum"))
    reg["margin_pct"] = (reg.profit / reg.revenue * 100).round(1)
    reg["revenue_share_pct"] = (reg.revenue / rev * 100).round(1); reg["profit_share_pct"] = (reg.profit / pro * 100).round(1)
    reg["lines_discounted_pct"] = (sl.groupby("region").discount.apply(lambda x: (x > 0).mean()) * 100).round(0)
    reg = reg.sort_values("revenue", ascending=False).reset_index()
    worst = reg.loc[reg.margin_pct.idxmin(), "region"]
    rest = df[df.region != worst]; rest_m = rest.profit.sum() / rest.sales.sum()
    wr = df[df.region == worst]
    gap_usd = (rest_m - wr.profit.sum() / wr.sales.sum()) * wr.sales.sum()

    sub = df.groupby(["category", "sub_category"]).agg(revenue=("sales", "sum"), profit=("profit", "sum")).reset_index()
    sub["margin_pct"] = (sub.profit / sub.revenue * 100).round(1)
    loss_sub = sub[sub.profit < 0].sort_values("profit")
    assert len(loss_sub) > 0 and set(hs.sub_category) <= set(loss_sub.sub_category)

    bands = pd.cut(sl.discount, [-1, 0, .1, .2, .3, .5, 1], labels=["0%", "1-10%", "11-20%", "21-30%", "31-50%", ">50%"])
    b = sl.groupby(bands, observed=True).agg(lines=("sales", "size"), revenue=("sales", "sum"), profit=("profit", "sum"),
                                              loss_lines_pct=("profit", lambda x: (x < 0).mean() * 100)).reset_index(names="discount")
    b["margin_pct"] = (b.profit / b.revenue * 100).round(1); b["loss_lines_pct"] = b.loss_lines_pct.round(0)
    assert b.margin_pct.is_monotonic_decreasing, "margin should fall with deeper discount bands"

    lp = sl[sl.sub_category.isin(loss_sub.sub_category)].groupby('sub_category').profit.apply(lambda x: (x < 0).mean() * 100)
    n_price, n_ship = int(df.is_price_outlier.sum()), int(df.ship_date_invalid.sum())
    n_rej = len(pd.read_csv(ROOT / 'data/processed/rejected_rows.csv'))
    fl = df[df.is_price_outlier == 1]
    # Illustrative what-if: cap every discount above 30% at 30%, same units sold, same unit cost
    hi = sl[sl.discount > .30]
    new_sales = hi.sales / (1 - hi.discount) * 0.70
    cap_gain = (new_sales - hi.sales).sum()
    cost_hi = (hi.sales - hi.profit).sum()
    out = [
        "# Business Insights and Recommendations\n",
        "> **Synthetic data.** The dataset was generated by `src/generate_synthetic_data.py`. These findings demonstrate the analytical method and do not describe a real business. "
        "Each number below is computed from `data/processed/superstore_clean.csv` by `src/generate_insights.py`; the SQL equivalents are named in brackets (e.g. Q07) and were reconciled in `reports/reconciliation_report.md`.\n",
        f"**Headline:** revenue USD {rev:,.0f}, profit USD {pro:,.0f}, margin {pro / rev:.1%}, "
        f"{df.order_id.nunique():,} orders (Q01-Q04).\n",
        "## 1. Which products generate the most revenue? (Q07)\n", md_table(fmt(top_rev)),
        "\n## 2. Which products generate the most profit? (Q08)\n", md_table(fmt(top_pro)),
        f"\nThe ten most profitable products produce {prod.nlargest(10, 'profit').profit.sum() / pro:.1%} of total profit.\n",
        "## 3. Which products have high sales but weak profitability? (notebook section 7)\n",
        f"Of {int((prod.revenue >= q75).sum())} products in the top revenue quartile (revenue of USD {q75:,.0f} or more), **{len(hs)} earn under 10% margin**. "
        f"Together they bring {hs.revenue.sum() / rev:.1%} of revenue and a combined profit of USD {hs.profit.sum():,.0f}.\n",
        md_table(fmt(hs)),
        "\n## 4. Which regions contribute most to revenue and profit? (Q10a)\n", md_table(reg.assign(revenue=reg.revenue.map("{:,.0f}".format), profit=reg.profit.map("{:,.0f}".format))),
        f"\n**{worst}** contributes {reg.loc[reg.region == worst, 'revenue_share_pct'].iat[0]}% of revenue but only {reg.loc[reg.region == worst, 'profit_share_pct'].iat[0]}% of profit.\n",
        "## 5. How do discounts relate to profitability? (Q13a)\n", md_table(b.assign(revenue=b.revenue.map("{:,.0f}".format), profit=b.profit.map("{:,.0f}".format))),
        "\nMargin falls with every step up in discount, and the relationship holds inside individual sub-categories (notebook section 8). "
        "This is an *association* in observational data; see the caution in the notebook before treating it as proof that removing discounts would restore profit.\n",
        "## 6. Which categories need management attention? (Q09b, Q11)\n", md_table(loss_sub.assign(revenue=loss_sub.revenue.map("{:,.0f}".format), profit=loss_sub.profit.map("{:,.0f}".format))),
        f"\nThese {len(loss_sub)} sub-categories hold {loss_sub.revenue.sum() / rev:.1%} of revenue and lose USD {-loss_sub.profit.sum():,.0f} in total.\n",
        "## 7. Opportunities and recommendations\n",
        "| # | Recommendation | Supporting metric | Estimate and its assumption |\n|---|---|---|---|\n"
        f"| 1 | Set a discount ceiling (for example 30%) and require approval above it | {len(hi):,} lines ({len(hi) / len(sl):.1%}) were discounted over 30% and lost USD {-hi.profit.sum():,.0f} (Q13a) | Capping those lines at 30% would add about USD {cap_gain:,.0f} of profit **if the same units still sold**. Treat as an upper bound: volume will likely fall |\n"
        f"| 2 | Review pricing and discount policy for {', '.join(loss_sub.sub_category)} | Net loss USD {-loss_sub.profit.sum():,.0f}; {lp.min():.0f}% to {lp.max():.0f}% of their sale lines lose money (Q09b) | Even undiscounted, thin margins leave little room to discount; a cost review may be needed (the data has no cost field to confirm) |\n"
        f"| 3 | Investigate discounting in the {worst} region | Margin {wr.profit.sum() / wr.sales.sum():.1%} vs {rest_m:.1%} elsewhere; {reg.loc[reg.region == worst, 'lines_discounted_pct'].iat[0]:.0f}% of lines discounted (Q10a) | Closing the margin gap would be worth about USD {gap_usd:,.0f} over the period, **assuming the region's product mix matches the others** |\n"
        f"| 4 | Report profit, not only revenue, in product rankings | {len(hs)} top-quartile revenue products earn under 10% margin | No estimate: this is a reporting change |\n"
        f"| 5 | Plan inventory and staffing for Q4 | Nov-Dec carry {df.groupby([df.order_date.dt.year, df.order_date.dt.month]).sales.sum().unstack().pipe(lambda m: m.div(m.sum(axis=1), axis=0)).mean()[[11, 12]].sum():.1%} of annual revenue (Q05a) | No estimate |\n"
        f"| 6 | Fix data entry controls for price and ship date | {n_price} suspected price keying errors, {n_ship} invalid ship dates, {n_rej} invalid rows quarantined (data quality report) | The flagged price lines hold {fl.sales.sum() / rev:.1%} of revenue and {fl.profit.sum() / pro:.1%} of profit that may be overstated |\n",
        "\n**How to read the estimates.** They are simple what-if calculations on this dataset, with the assumption stated beside each. They are not forecasts.\n",
        "## Limitations\n- Synthetic data: no real-world conclusions.\n- No cost, inventory or returns-reason fields, so the causes of low margin cannot be separated into price versus cost.\n"
        "- One country, four years, one currency.\n- Customer 'new vs returning' is censored at the start of the data window.\n"]
    (ROOT / "reports/business_insights.md").write_text("\n".join(out), encoding="utf-8")
    print("wrote reports/business_insights.md")


if __name__ == "__main__":
    main()
